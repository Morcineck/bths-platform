CREATE TABLE viagens
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidade      VARCHAR(255),
    data_fim    DATE         NOT NULL,
    data_inicio DATE         NOT NULL,
    endereco    VARCHAR(255),
    estado      VARCHAR(255),
    evento      VARCHAR(255) NOT NULL,
    nome        VARCHAR(255) NOT NULL,
    status      VARCHAR(255) NOT NULL
        CONSTRAINT ck_viagens_status
            CHECK (status IN ('CANCELADA', 'EM_ANDAMENTO', 'FINALIZADA', 'PLANEJADA'))
);

CREATE TABLE usuarios
(
    id     UUID PRIMARY KEY,
    ativo  BOOLEAN      NOT NULL,
    email  VARCHAR(255) NOT NULL
        CONSTRAINT uk_usuarios_email UNIQUE,
    nome   VARCHAR(255) NOT NULL,
    perfil VARCHAR(255) NOT NULL
        CONSTRAINT ck_usuarios_perfil
            CHECK (perfil IN ('ADMIN', 'HOSPEDE', 'STAFF')),
    senha  VARCHAR(255) NOT NULL
);

CREATE TABLE motoristas
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo         BOOLEAN      NOT NULL,
    nome_completo VARCHAR(255) NOT NULL,
    observacao    TEXT,
    telefone      VARCHAR(255)
);

CREATE TABLE veiculos
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo                  BOOLEAN      NOT NULL,
    capacidade_passageiros INTEGER      NOT NULL,
    modelo                 VARCHAR(255) NOT NULL,
    observacao             TEXT,
    placa                  VARCHAR(7)   NOT NULL
        CONSTRAINT uk_veiculos_placa UNIQUE
);

CREATE TABLE hospedagens
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidade             VARCHAR(255),
    contato_nome       VARCHAR(255),
    contato_telefone   VARCHAR(255),
    endereco           VARCHAR(255),
    estado             VARCHAR(255),
    horario_check_in   TIME,
    horario_check_out  TIME,
    imagem_url         VARCHAR(255),
    localizacao_url    VARCHAR(255),
    nome               VARCHAR(255) NOT NULL,
    observacao_publica VARCHAR(1000),
    wifi_nome          VARCHAR(255),
    wifi_senha         VARCHAR(255),
    viagens_id         BIGINT       NOT NULL
        CONSTRAINT fk_hospedagens_viagem REFERENCES viagens (id)
);

CREATE TABLE hospedes
(
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf                            VARCHAR(11)  NOT NULL,
    data_nascimento                DATE,
    email                          VARCHAR(255),
    horario_previsto_chegada       TIMESTAMP(6),
    nome_completo                  VARCHAR(255) NOT NULL,
    status_check_in                VARCHAR(255) NOT NULL
        CONSTRAINT ck_hospedes_status_check_in
            CHECK (status_check_in IN ('NAO_COMPARECEU', 'PENDENTE', 'REALIZADO')),
    telefone                       VARCHAR(255),
    viagem_id                      BIGINT       NOT NULL
        CONSTRAINT fk_hospedes_viagem REFERENCES viagens (id),
    data_hora_check_in             TIMESTAMP(6),
    observacao_check_in            VARCHAR(255),
    responsavel_check_in           VARCHAR(255),
    codigo_check_in                VARCHAR(255)
        CONSTRAINT uk_hospedes_codigo_check_in UNIQUE,
    data_hora_nao_comparecimento   TIMESTAMP(6),
    motivo_nao_comparecimento      VARCHAR(255),
    responsavel_nao_comparecimento VARCHAR(255),
    usuario_id                     UUID
        CONSTRAINT fk_hospedes_usuario REFERENCES usuarios (id),
    CONSTRAINT uk_hospede_cpf_viagem UNIQUE (cpf, viagem_id)
);

CREATE TABLE quartos
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacidade    INTEGER      NOT NULL,
    nome          VARCHAR(255) NOT NULL,
    status        VARCHAR(255) NOT NULL
        CONSTRAINT ck_quartos_status
            CHECK (status IN ('DISPONIVEL', 'INDISPONIVEL', 'LOTADO')),
    tipo          VARCHAR(255) NOT NULL
        CONSTRAINT ck_quartos_tipo
            CHECK (tipo IN ('ALOJAMENTO', 'SUITE')),
    viagem_id     BIGINT       NOT NULL
        CONSTRAINT fk_quartos_viagem REFERENCES viagens (id),
    hospedagem_id BIGINT
        CONSTRAINT fk_quartos_hospedagem REFERENCES hospedagens (id)
);

CREATE TABLE agenda_viagem
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo            BOOLEAN      NOT NULL,
    data_hora_fim    TIMESTAMP(6),
    data_hora_inicio TIMESTAMP(6) NOT NULL,
    descricao        VARCHAR(1000),
    ordem            INTEGER      NOT NULL,
    tipo             VARCHAR(255) NOT NULL
        CONSTRAINT ck_agenda_viagem_tipo
            CHECK (tipo IN ('CHECK_IN', 'CHECK_OUT', 'CHEGADA', 'FESTIVAL', 'OUTRO', 'WELCOME_BEAT')),
    titulo           VARCHAR(255) NOT NULL,
    visivel_hospede  BOOLEAN      NOT NULL,
    viagem_id        BIGINT       NOT NULL
        CONSTRAINT fk_agenda_viagem_viagem REFERENCES viagens (id)
);

CREATE TABLE avisos
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo           BOOLEAN      NOT NULL,
    data_publicacao TIMESTAMP(6) NOT NULL,
    mensagem        VARCHAR(255) NOT NULL,
    tipo            VARCHAR(255) NOT NULL
        CONSTRAINT ck_avisos_tipo
            CHECK (tipo IN ('EVENTO', 'HOSPEDAGEM', 'IMPORTANTE', 'INFORMATIVO', 'TRANSPORTE')),
    titulo          VARCHAR(255) NOT NULL,
    viagem_id       BIGINT       NOT NULL
        CONSTRAINT fk_avisos_viagem REFERENCES viagens (id)
);

CREATE TABLE alocacao_quartos
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_alocacao TIMESTAMP(6) NOT NULL,
    hospede_id    BIGINT       NOT NULL
        CONSTRAINT fk_alocacao_quartos_hospede REFERENCES hospedes (id),
    quarto_id     BIGINT       NOT NULL
        CONSTRAINT fk_alocacao_quartos_quarto REFERENCES quartos (id),
    viagem_id     BIGINT       NOT NULL
        CONSTRAINT fk_alocacao_quartos_viagem REFERENCES viagens (id),
    tipo_cama     VARCHAR(255)
        CONSTRAINT ck_alocacao_quartos_tipo_cama
            CHECK (tipo_cama IN ('BELICHE', 'CASAL')),
    CONSTRAINT uk_alocacao_hospede_viagem UNIQUE (hospede_id, viagem_id)
);

CREATE TABLE operacoes_traslado
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motorista_id       BIGINT
        CONSTRAINT fk_operacoes_traslado_motorista REFERENCES motoristas (id),
    veiculo_id         BIGINT
        CONSTRAINT fk_operacoes_traslado_veiculo REFERENCES veiculos (id),
    viagem_id          BIGINT       NOT NULL
        CONSTRAINT fk_operacoes_traslado_viagem REFERENCES viagens (id),
    aeroporto          VARCHAR(255)
        CONSTRAINT ck_operacoes_traslado_aeroporto
            CHECK (aeroporto IN ('CGH', 'GRU', 'VCP')),
    local_destino      VARCHAR(255) NOT NULL,
    local_origem       VARCHAR(255) NOT NULL,
    observacao         TEXT,
    status             VARCHAR(255) NOT NULL
        CONSTRAINT ck_operacoes_traslado_status
            CHECK (status IN ('AGUARDANDO', 'CANCELADO', 'CONCLUIDO', 'EM_ANDAMENTO')),
    tipo               VARCHAR(255) NOT NULL
        CONSTRAINT ck_operacoes_traslado_tipo
            CHECK (tipo IN ('AEROPORTO_PARA_HOSPEDAGEM', 'HOSPEDAGEM_PARA_AEROPORTO', 'OUTRO')),
    data_hora_prevista TIMESTAMP(6) NOT NULL,
    orientacao_hospede TEXT
);

CREATE TABLE traslados
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aeroporto            VARCHAR(255)
        CONSTRAINT ck_traslados_aeroporto
            CHECK (aeroporto IN ('CGH', 'GRU', 'VCP')),
    companhia_aerea      VARCHAR(255),
    data_hora_prevista   TIMESTAMP(6) NOT NULL,
    local_destino        VARCHAR(255) NOT NULL,
    local_origem         VARCHAR(255) NOT NULL,
    numero_voo           VARCHAR(255),
    observacao           TEXT,
    status               VARCHAR(255) NOT NULL
        CONSTRAINT ck_traslados_status
            CHECK (status IN ('AGUARDANDO', 'CANCELADO', 'CONCLUIDO', 'EM_ANDAMENTO')),
    tipo                 VARCHAR(255) NOT NULL
        CONSTRAINT ck_traslados_tipo
            CHECK (tipo IN ('AEROPORTO_PARA_HOSPEDAGEM', 'HOSPEDAGEM_PARA_AEROPORTO', 'OUTRO')),
    hospede_id           BIGINT       NOT NULL
        CONSTRAINT fk_traslados_hospede REFERENCES hospedes (id),
    viagem_id            BIGINT       NOT NULL
        CONSTRAINT fk_traslados_viagem REFERENCES viagens (id),
    motorista_id         BIGINT
        CONSTRAINT fk_traslados_motorista REFERENCES motoristas (id),
    veiculo_id           BIGINT
        CONSTRAINT fk_traslados_veiculo REFERENCES veiculos (id),
    operacao_traslado_id BIGINT
        CONSTRAINT fk_traslados_operacao REFERENCES operacoes_traslado (id),
    orientacao_hospede   TEXT
);

CREATE TABLE historico_status_operacao_traslado
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora            TIMESTAMP(6) NOT NULL,
    motivo               VARCHAR(255) NOT NULL,
    novo_status          VARCHAR(255) NOT NULL
        CONSTRAINT ck_hist_status_operacao_novo
            CHECK (novo_status IN ('AGUARDANDO', 'CANCELADO', 'CONCLUIDO', 'EM_ANDAMENTO')),
    status_anterior      VARCHAR(255) NOT NULL
        CONSTRAINT ck_hist_status_operacao_anterior
            CHECK (status_anterior IN ('AGUARDANDO', 'CANCELADO', 'CONCLUIDO', 'EM_ANDAMENTO')),
    operacao_traslado_id BIGINT       NOT NULL
        CONSTRAINT fk_hist_status_operacao_operacao REFERENCES operacoes_traslado (id)
);

CREATE TABLE historico_status_traslado
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora         TIMESTAMP(6) NOT NULL,
    motivo            VARCHAR(255) NOT NULL,
    novo_status       VARCHAR(255) NOT NULL
        CONSTRAINT ck_hist_status_traslado_novo
            CHECK (novo_status IN ('AGUARDANDO', 'CANCELADO', 'CONCLUIDO', 'EM_ANDAMENTO')),
    traslado_anterior VARCHAR(255) NOT NULL
        CONSTRAINT ck_hist_status_traslado_anterior
            CHECK (traslado_anterior IN ('AGUARDANDO', 'CANCELADO', 'CONCLUIDO', 'EM_ANDAMENTO')),
    traslado_id       BIGINT       NOT NULL
        CONSTRAINT fk_hist_status_traslado_traslado REFERENCES traslados (id)
);

CREATE INDEX ix_hospedagens_viagem ON hospedagens (viagens_id);
CREATE INDEX ix_hospedes_viagem ON hospedes (viagem_id);
CREATE INDEX ix_hospedes_usuario ON hospedes (usuario_id);
CREATE INDEX ix_quartos_viagem ON quartos (viagem_id);
CREATE INDEX ix_quartos_hospedagem ON quartos (hospedagem_id);
CREATE INDEX ix_agenda_viagem_viagem ON agenda_viagem (viagem_id);
CREATE INDEX ix_avisos_viagem ON avisos (viagem_id);
CREATE INDEX ix_alocacao_quartos_quarto ON alocacao_quartos (quarto_id);
CREATE INDEX ix_alocacao_quartos_viagem ON alocacao_quartos (viagem_id);
CREATE INDEX ix_operacoes_traslado_motorista ON operacoes_traslado (motorista_id);
CREATE INDEX ix_operacoes_traslado_veiculo ON operacoes_traslado (veiculo_id);
CREATE INDEX ix_operacoes_traslado_viagem ON operacoes_traslado (viagem_id);
CREATE INDEX ix_traslados_hospede ON traslados (hospede_id);
CREATE INDEX ix_traslados_viagem ON traslados (viagem_id);
CREATE INDEX ix_traslados_motorista ON traslados (motorista_id);
CREATE INDEX ix_traslados_veiculo ON traslados (veiculo_id);
CREATE INDEX ix_traslados_operacao ON traslados (operacao_traslado_id);
CREATE INDEX ix_hist_status_operacao_operacao ON historico_status_operacao_traslado (operacao_traslado_id);
CREATE INDEX ix_hist_status_traslado_traslado ON historico_status_traslado (traslado_id);